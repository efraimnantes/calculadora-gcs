def celsius_para_fahrenheit(celsius):
    """Converte Celsius para Fahrenheit."""
    return (celsius * 9 / 5) + 32


def km_para_milhas(km):
    """Converte quilômetros para milhas."""
    return km * 0.621371


def kg_para_libras(kg):
    """Converte quilogramas para libras."""
    return kg * 2.20462
